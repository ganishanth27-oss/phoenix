import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react()],
  server: {
    host: true,
    port: 5173,
    proxy: {
      '/api': {
        target: 'http://localhost:8000',
        changeOrigin: true,
        secure: false,
        ws: true,
        configure: (proxy, _options) => {
          proxy.on('error', (err, _req, res) => {
            // Log graceful notice without throwing uncaught exceptions to client
            if (res && !res.headersSent) {
              res.writeHead(503, { 'Content-Type': 'application/json' });
              res.end(JSON.stringify({
                success: false,
                error: 'Unable to connect to Phoenix Solutions server. Please ensure the backend is running.',
                message: 'Unable to connect to Phoenix Solutions server. Please try again shortly.'
              }));
            }
          });
        },
      },
    },
  },
})

